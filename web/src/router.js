// Canonical Goosh routes for browser and Capacitor (Android/iOS).
// One route table; no separate native router or hash-only navigation model.
const PATHS = Object.freeze({ home: '/', studio: '/etudes', practice: '/practice' });
const PAGE_FOR_PATH = Object.freeze({
  etudes: 'studio', practice: 'practice'
});
const LEGACY_PAGES = Object.freeze({studio:'studio',practice:'practice'});
let onNavigation = null;

export function routePath(page, id = null) {
  if (!Object.hasOwn(PATHS, page)) throw new Error('Unknown page: ' + page);
  if (page === 'home') return PATHS.home;
  if (id == null || id === '') return PATHS[page];
  return PATHS[page] + '/' + encodeURIComponent(String(id));
}

export function readRoute() {
  const path = location.pathname;
  if (path === '/' || path === '/index.html') return {page:'home', id:null};
  const matched = /^\/(etudes|practice)(?:\/([^/]+))?\/?$/.exec(path);
  if (!matched) return {page:'home', id:null};
  try {
    const id = matched[2] ? decodeURIComponent(matched[2]) : null;
    return {page:PAGE_FOR_PATH[matched[1]],id};
  } catch {
    return {page:'home',id:null};
  }
}

// Upgrade shared links generated by older versions: /#studio/id -> /etudes/id.
// Replace history in place, preserving Back entries and non-route query params.
export function upgradeLegacyHash() {
  if (location.pathname !== '/' && location.pathname !== '/index.html') return false;
  const matched = /^#\/?(studio|practice)(?:\/([^/?#]+))?\/?$/.exec(location.hash);
  if (!matched || !Object.hasOwn(LEGACY_PAGES, matched[1])) return false;
  let id = null;
  if (matched[2]) {
    try { id = decodeURIComponent(matched[2]); }
    catch { return false; }
  }
  history.replaceState(history.state, '', routePath(LEGACY_PAGES[matched[1]], id) + location.search);
  return true;
}

export function navigateTo(page, id = null, {replace = false} = {}) {
  const destination = routePath(page, id);
  if (location.pathname === destination && !location.hash) return false;
  if (replace) history.replaceState(history.state, '', destination + location.search);
  else history.pushState(null, '', destination + location.search);
  onNavigation?.();
  return true;
}

export function listenToRoutes(callback) {
  onNavigation = callback;
  const handlePop = () => callback();
  const handleLegacy = () => {
    if (upgradeLegacyHash()) callback();
  };
  window.addEventListener('popstate', handlePop);
  window.addEventListener('hashchange', handleLegacy);
  return () => {
    window.removeEventListener('popstate', handlePop);
    window.removeEventListener('hashchange', handleLegacy);
    if (onNavigation === callback) onNavigation = null;
  };
}
